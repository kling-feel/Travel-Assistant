def city_zh(city: str) -> str:
    return CITY_ZH.get(city, city)


def airport_zh(code: str, city: str) -> str:
    return AIRPORT_NAMES.get(code, f"{city_zh(city)}机场" if city else code or "机场")


def product_zh(name: str, *, city: str = "", airport: str = "") -> str:
    """Only relabel products generated by this project; preserve unknown names."""
    hotel = re.fullmatch(r"虚构·(.+)机场周边酒店 ([123])", name)
    if hotel:
        place = city_zh(city or hotel.group(1))
        tier = ("", "悦居", "悠享", "臻选")[int(hotel.group(2))]
        return f"{place}机场周边酒店 · {tier}"
    rental = re.fullmatch(r"虚构·([A-Z]{3})机场租车 ([12])", name)
    if rental:
        place = airport_zh(airport or rental.group(1), city)
        return f"{place}租车 · {'经济型' if rental.group(2) == '1' else '舒适型'}"
    return name


